import { LocalizedText, SiteLanguage } from '../models/artwork.model';
import {
  Exhibition,
  ExhibitionMedia,
  ExhibitionMediaKind,
  ExhibitionPublication,
} from '../models/exhibition.model';

type Triplet = readonly [en: string, fr: string, ko: string];

interface ExhibitionInput {
  city: Triplet;
  country: Triplet;
  dates?: Triplet;
  description: Triplet;
  details?: Triplet[];
  featured?: boolean;
  media?: ExhibitionMedia[];
  publications?: ExhibitionPublication[];
  slug: string;
  status?: Triplet;
  title: Triplet;
  type: Triplet;
  venue: Triplet;
  year: string;
}

const t = ([en, fr, ko]: Triplet): LocalizedText => ({ en, fr, ko });
const same = (value: string): Triplet => [value, value, value];
const yearOnly = (year: string): Triplet => [year, year, `${year}년`];

const media = (
  kind: ExhibitionMediaKind,
  src: string,
  alt: Triplet,
  caption?: Triplet,
): ExhibitionMedia => ({
  kind,
  src,
  alt: t(alt),
  ...(caption ? { caption: t(caption) } : {}),
});

const publication = (
  type: ExhibitionPublication['type'],
  title: Triplet,
  source: Triplet,
  href: string,
  date?: string,
): ExhibitionPublication => ({
  type,
  title: t(title),
  source: t(source),
  href,
  ...(date ? { date } : {}),
});

const artistArchive = (): ExhibitionPublication =>
  publication(
    'website',
    [
      'Artist website: exhibition archive and CV',
      'Site de l’artiste : archives des expositions et CV',
      '작가 웹사이트: 전시 아카이브 및 이력',
    ],
    ['Francesca Cho', 'Francesca Cho', '조 프란체스카'],
    'https://francescacho.com/#Bio',
  );

const exhibition = (input: ExhibitionInput): Exhibition => ({
  slug: input.slug,
  title: t(input.title),
  year: input.year,
  dates: t(input.dates ?? yearOnly(input.year)),
  city: t(input.city),
  country: t(input.country),
  venue: t(input.venue),
  type: t(input.type),
  description: t(input.description),
  details: input.details?.map(t),
  media: input.media ?? [],
  publications: [artistArchive(), ...(input.publications ?? [])],
  featured: input.featured ?? false,
  ...(input.status ? { status: t(input.status) } : {}),
});

